const toCharacter = (c: Costume): Character => ({
  key: `inf-${c.key}`,
  color: c.color,
  matches: run => c.agent !== null && run.type === c.agent,
  draw: f => {
    body(f)
    if (c.held) stamp(f, 22, 5, c.held, 'it')
    if (c.head) stamp(f, c.headAt[0], c.headAt[1], c.head, 'hd')
  },
  css: `.c-inf-${c.key}.run .it,.c-inf-${c.key}.run .hd{${ANIM_CSS[c.anim]}}`,
})

/** The 25 agent costumes, in table order: first in CHARACTERS. */
export const AGENT_CHARACTERS: readonly Character[] = COSTUMES.filter(c => c.agent !== null).map(toCharacter)

/** The variants a second or later concurrent run of the same agent wears. */
export const VARIANT_CHARACTERS: readonly Character[] = COSTUMES.filter(c => c.agent === null).map(c => ({ ...toCharacter(c), matches: () => false }))
