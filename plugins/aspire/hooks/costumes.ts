// Influencer-marketing costumes for the crabs: one per Aspire agent type (25), and
// seven variants worn by the second and later concurrent runs of the same agent.
// Each costume is a pixel prop held in the right claw (8 by 9 cells, drawn at
// 22,5) and, for some, a head piece (14 wide, at its own position). They are
// drawn on the same 30 by 28 grid as ./characters.ts, so the two stay in step.
//
// To add one: add an entry to COSTUMES; its `agent` is the agent type it stands
// for, or null for a variant. Cells use the PALETTE letters; `.` is empty.

import type { Character, Fill } from './characters'

const PALETTE: Record<string, string> = {
  k: '#1F1E1D', w: '#F8F6F1', g: '#C9CCD2', d: '#55514C', y: '#F5C542', a: '#EF9F27', r: '#E24B4A',
  b: '#378ADD', l: '#85B7EB', t: '#1D9E75', p: '#D4537E', o: '#D85A30', v: '#7F77DD', n: '#7A4A26',
}
const BODY = '#3B8A82'
const INK = '#1F1E1D'

export type Anim = 'sway' | 'bounce' | 'pulse' | 'blink' | 'spin'

export type Costume = {
  key: string
  name: string
  /** The agent type that wears it, or null for a variant. */
  agent: string | null
  /** The accent: the agent type label, the status dot and the card's marker. */
  color: string
  anim: Anim
  held: readonly string[] | null
  head: readonly string[] | null
  headAt: readonly [number, number]
}

const stamp = (f: Fill, x: number, y: number, rows: readonly string[], cls: string): void =>
  rows.forEach((row, dy) => [...row].forEach((ch, dx) => PALETTE[ch] && f(x + dx, y + dy, 1, 1, PALETTE[ch] ?? '', cls)))

const ANIM_CSS: Record<Anim, string> = {
  sway: 'transform-origin:50% 100%;animation:cs-sway .6s ease-in-out infinite',
  bounce: 'animation:cs-bounce .5s steps(1) infinite',
  pulse: 'transform-origin:50% 50%;animation:cs-pulse .8s ease-in-out infinite',
  blink: 'animation:cs-blink 1s steps(1) infinite',
  spin: 'transform-origin:50% 50%;animation:cs-spin 2s linear infinite',
}

/** Shared keyframes for the costumes' motion; included once in CRAB_CSS. */
export const COSTUME_KEYFRAMES = `@keyframes cs-sway{50%{transform:rotate(14deg)}}@keyframes cs-bounce{50%{transform:translateY(-2px)}}
@keyframes cs-pulse{50%{transform:scale(1.18)}}@keyframes cs-blink{50%{opacity:.35}}@keyframes cs-spin{to{transform:rotate(360deg)}}`

const body = (f: Fill): void => {
  f(7, 10, 16, 12, BODY)
  f(3, 14, 4, 4, BODY)
  f(23, 14, 4, 4, BODY)
  f(9, 12, 2, 2, INK)
  f(19, 12, 2, 2, INK)
  f(7, 22, 2, 4, BODY, 'la')
  f(17, 22, 2, 4, BODY, 'la')
  f(11, 22, 2, 4, BODY, 'lb')
  f(21, 22, 2, 4, BODY, 'lb')
}

